/** Map AI / trip interest chips onto POI categories. */
export function categoriesForInterest(interest) {
  const map = {
    nature: [
      'nature',
      'waterfall',
      'spring',
      'river',
      'lake',
      'garden',
      'park',
      'valley',
      'gorge',
      'peak',
      'geology',
    ],
    history: ['heritage', 'history', 'geology', 'museum'],
    culture: ['village', 'culture', 'market', 'heritage', 'museum'],
    family: ['garden', 'park', 'lake', 'waterfall', 'spring', 'market', 'museum'],
  };
  return map[interest] || [interest];
}

export function poiMatchesInterest(poiCategory, interests) {
  if (!interests?.length) return true;
  return interests.some((interest) =>
    categoriesForInterest(interest).includes(poiCategory)
  );
}


